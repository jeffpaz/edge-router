#!/usr/bin/env python3
"""Export the PazBrain wiki to the Mac mini's private index.

Reads the wiki markdown directly (~/pazbrain/wiki/<category>/<slug>.md): the full pages,
rather than the Logseq "pazbrain" graph, which holds a thinner mirror of them. The same
pages as logseq_ingest.py are used: index.md, log.md, _archive/ and dot paths are skipped.
Each page becomes `# title`, one metadata line, the summary, then the body.

One way only: Jetson → mini. This script only reads the wiki. The pages go to the mini as
one tar stream over SSH with a dedicated key that, on the mini, can only run PazRAG's
scripts/pazbrain_receive.sh (it takes the export and re-indexes; nothing comes back but
counts). The mini holds no key for this host.

Each run builds a deterministic tar. When it is identical to the last pushed export,
nothing is sent. An export with no pages, or with fewer than half the pages of the last
push, is not sent (a broken sync must not empty the index); --force overrides.

    export_for_mini.py              # export and push if changed (pazbrain-mini-export.service)
    export_for_mini.py --dry-run    # export only; print counts
    export_for_mini.py --force      # push even if unchanged or much smaller

Logs carry counts, sizes and timings only — never page titles or text.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
import re
import subprocess
import sys
import tarfile
import time
from pathlib import Path

import yaml

WIKI = Path(os.environ.get("PAZBRAIN_WIKI", str(Path.home() / "pazbrain" / "wiki")))
SKIP_FILES = {"index.md", "log.md"}  # same as logseq_ingest.py: generated by the API
SKIP_DIRS = {"_archive"}             # retired pages and snapshots
META_FIELDS = ("category", "tags", "updated", "confidence")
MANIFEST = ".manifest.json"

MINI = os.environ.get("PAZBRAIN_MINI_SSH", "jeffpaz@192.168.11.60")
KEY = Path(os.environ.get("PAZBRAIN_MINI_KEY", str(Path.home() / ".ssh" / "pazbrain_to_mini")))
STATE = Path(os.environ.get("PAZBRAIN_MINI_STATE", "/opt/pazbrain/run/mini-export.json"))
PUSH_TIMEOUT_S = 900  # the mini re-indexes changed pages before answering

_UNSAFE = re.compile(r"[/\\\x00-\x1f\x7f:]")


class ExportError(RuntimeError):
    pass


def log(msg: str) -> None:
    print(msg, file=sys.stderr, flush=True)


def parse_page(text: str) -> tuple[dict, str]:
    """(frontmatter, body). A page without frontmatter is all body."""
    if text.startswith("---\n"):
        end = text.find("\n---", 4)
        if end > 0:
            fm = yaml.safe_load(text[4:end]) or {}
            if not isinstance(fm, dict):
                raise ValueError("frontmatter is not a mapping")
            return fm, text[end + 4:].lstrip("\n")
    return {}, text


def _flat(v) -> str:
    return ", ".join(str(x) for x in v) if isinstance(v, (list, tuple)) else str(v)


def render(path: Path, fm: dict, body: str) -> tuple[str, str]:
    """(title, markdown)."""
    title = str(fm.get("title") or path.stem.replace("-", " ")).strip()
    meta = " · ".join(f"{k.capitalize()}: {_flat(fm[k])}" for k in META_FIELDS if fm.get(k) not in (None, "", []))
    lines = [f"# {title}", ""]
    if meta:
        lines += [meta, ""]
    if fm.get("summary"):
        lines += [f"Summary: {_flat(fm['summary']).strip()}", ""]
    body = body.strip()
    if body.startswith("# "):  # the body's own title line duplicates ours
        body = body.split("\n", 1)[1].strip() if "\n" in body else ""
    lines.append(body)
    return title, "\n".join(lines).rstrip() + "\n"


def wiki_pages(root: Path = None) -> list[Path]:
    root = root or WIKI
    out = []
    for path in sorted(root.rglob("*.md")):
        parts = path.relative_to(root).parts
        if path.name in SKIP_FILES or SKIP_DIRS & set(parts) or any(p.startswith(".") for p in parts):
            continue
        out.append(path)
    return out


def file_name(title: str, used: set[str]) -> str:
    base = _UNSAFE.sub("_", title).strip().strip(".")[:150] or "untitled"
    name, n = f"{base}.md", 2
    while name.casefold() in used:
        name, n = f"{base} ({n}).md", n + 1
    used.add(name.casefold())
    return name


def export(root: Path = None) -> tuple[dict[str, bytes], int]:
    """({file name: markdown}, pages skipped as unreadable)."""
    rendered, skipped = [], 0
    for path in wiki_pages(root):
        try:
            fm, body = parse_page(path.read_text(encoding="utf-8", errors="replace"))
        except (ValueError, yaml.YAMLError):
            skipped += 1
            continue
        rendered.append(render(path, fm, body))
    pages: dict[str, bytes] = {}
    used: set[str] = set()
    for title, md in sorted(rendered, key=lambda r: r[0].casefold()):
        pages[file_name(title, used)] = md.encode()
    return pages, skipped


def build_tar(pages: dict[str, bytes]) -> bytes:
    """Deterministic: same pages, same bytes (sorted, fixed mtime/owner/mode)."""
    files = {**pages, MANIFEST: json.dumps({"source": "wiki", "pages": len(pages)}, sort_keys=True).encode()}
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.PAX_FORMAT) as tar:
        for name in sorted(files):
            info = tarfile.TarInfo(name)
            info.size, info.mtime, info.mode, info.uid, info.gid = len(files[name]), 0, 0o644, 0, 0
            tar.addfile(info, io.BytesIO(files[name]))
    return buf.getvalue()


def load_state() -> dict:
    try:
        return json.loads(STATE.read_text())
    except (OSError, ValueError):
        return {}


def save_state(state: dict) -> None:
    STATE.parent.mkdir(parents=True, exist_ok=True)
    tmp = STATE.with_suffix(".tmp")
    tmp.write_text(json.dumps(state))
    os.replace(tmp, STATE)


def push(data: bytes) -> str:
    argv = ["ssh", "-i", str(KEY), "-o", "IdentitiesOnly=yes", "-o", "BatchMode=yes",
            "-o", "StrictHostKeyChecking=yes", "-o", "ConnectTimeout=10", MINI, "pazbrain-receive"]
    proc = subprocess.run(argv, input=data, capture_output=True, timeout=PUSH_TIMEOUT_S)
    if proc.returncode != 0:
        detail = proc.stderr.decode(errors="replace").strip().splitlines()[-1:] or [""]
        raise ExportError(f"push exited {proc.returncode}: {detail[0][:200]}")
    return proc.stdout.decode(errors="replace").strip()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)

    t0 = time.monotonic()
    if not WIKI.is_dir():
        log(f"export failed: no wiki at {WIKI}")
        return 1
    pages, skipped = export()
    data = build_tar(pages)
    digest = hashlib.sha256(data).hexdigest()
    state = load_state()
    log(f"exported pages={len(pages)} skipped={skipped} bytes={len(data)} seconds={time.monotonic() - t0:.1f}")
    if args.dry_run:
        return 0
    if not args.force:
        if not pages:
            log("not pushed: the export has no pages")
            return 1
        last = state.get("pages") or 0
        if last >= 10 and len(pages) < last / 2:
            log(f"not pushed: {len(pages)} pages vs {last} last time (use --force if intended)")
            return 1
        if state.get("sha256") == digest:
            log("unchanged since the last push: nothing sent")
            return 0
    try:
        reply = push(data)
    except (ExportError, subprocess.TimeoutExpired) as exc:
        log(f"push failed: {type(exc).__name__}: {exc}")
        return 1
    save_state({"sha256": digest, "pages": len(pages), "pushed_at": int(time.time())})
    log(f"pushed; mini replied {reply[:500]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
