#!/usr/bin/env python3
"""PazBrain wiki -> Logseq DB graph "pazbrain" (one way, idempotent).

Reads every <category>/<slug>.md under ~/pazbrain/wiki (the pages the sync job lands via
the PazBrain API) and upserts each as a Logseq page named by its slug, so the wiki's
[[slug]] links become real page refs. Frontmatter goes into pazbrain-* page properties
(summary -> the built-in description), the body goes in as blocks, and every page is
tagged #pazbrain. index.md, log.md and _archive/ are skipped.

Idempotent: each page carries pazbrain-sha (sha256 of the source file). Unchanged pages
are skipped; changed pages have their content blocks replaced. The sha is written last,
so an interrupted run redoes that page next time. Pages whose wiki file is gone are
reported, never removed.

    logseq_ingest.py              # ingest
    logseq_ingest.py --dry-run    # print what would change, write nothing

The db-worker-node daemon is stopped at the end if this run started it.

Page bodies are never printed or logged.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
from datetime import date, datetime
from pathlib import Path

import yaml

WIKI = Path.home() / "pazbrain" / "wiki"
GRAPH = "pazbrain"
LOGSEQ = str(Path.home() / ".local" / "bin" / "logseq")
SKIP_FILES = {"index.md", "log.md"}  # generated by the API on every write
SKIP_DIRS = {"_archive"}  # retired pages and timestamped snapshots sharing a live slug
OUTLINE_LINE = re.compile(r"^\s*([-*+] |#{1,6} )")
# A '#' that the Logseq parser would read as a tag (e.g. "Item #42", "docs/#anchor"); headings don't match.
TAG_LIKE = re.compile(r"(?<![\w&#])#(?=[^\s#])")
# Left as-is: Logseq parses these as links / code, so a '#' inside them is never a tag.
PROTECTED = re.compile(r"`[^`]*`|\b[a-z][a-z0-9+.-]*://\S+", re.I)
TAG = "pazbrain"
# frontmatter key -> Logseq property name (all default type, cardinality one)
PROPS = {
    "title": "pazbrain-title",
    "category": "pazbrain-category",
    "tags": "pazbrain-tags",
    "confidence": "pazbrain-confidence",
    "updated": "pazbrain-updated",
}
SOURCE_PROP = "pazbrain-source"
SHA_PROP = "pazbrain-sha"
TIMEOUT_MS = "30000"


class LogseqError(RuntimeError):
    pass


def logseq(*args: str, parse: bool = True):
    env = dict(os.environ, NODE_NO_WARNINGS="1")
    proc = subprocess.run(
        [LOGSEQ, *args, "--graph", GRAPH, "--output", "json", "--timeout-ms", TIMEOUT_MS],
        capture_output=True, text=True, env=env, timeout=180,
    )
    out = proc.stdout.strip()
    try:
        resp = json.loads(out) if out else {}
    except json.JSONDecodeError:
        resp = {}
    if proc.returncode != 0 or resp.get("status") not in (None, "ok"):
        msg = (resp.get("error") or {}).get("message") if isinstance(resp.get("error"), dict) else resp.get("error")
        raise LogseqError(f"logseq {args[0]} {args[1] if len(args) > 1 else ''}: "
                          f"{msg or (proc.stderr.strip().splitlines() or ['exit %d' % proc.returncode])[-1]}")
    return resp.get("data") if parse else resp


def edn_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)  # JSON string escaping is valid EDN


def _plain(value):
    if isinstance(value, (datetime, date)):
        return value.isoformat()
    if isinstance(value, list):
        return [_plain(v) for v in value]
    return value


def parse_page(text: str) -> tuple[dict, str]:
    """Same frontmatter rules as pazbrain_sync.parse_page."""
    text = text.lstrip("﻿")
    m = re.match(r"^---[ \t]*\r?\n(.*?)\r?\n---[ \t]*(?:\r?\n|$)(.*)$", text, re.S)
    if not m:
        raise ValueError("no YAML frontmatter")
    fm = yaml.safe_load(m.group(1)) or {}
    if not isinstance(fm, dict):
        raise ValueError("frontmatter is not a mapping")
    return {str(k): _plain(v) for k, v in fm.items()}, m.group(2)


def escape_tags(line: str) -> str:
    """Swap tag-like '#' for a fullwidth '＃' outside URLs and inline code."""
    out, pos = [], 0
    for m in PROTECTED.finditer(line):
        out += [TAG_LIKE.sub("＃", line[pos:m.start()]), m.group()]
        pos = m.end()
    out.append(TAG_LIKE.sub("＃", line[pos:]))
    return "".join(out)


def to_outline(body: str) -> str:
    """The CLI's markdown import takes only bullets and headings: turn paragraph lines into
    bullets, and escape tag-like '#' so "#42" stays text, not a tag."""
    out = []
    for line in body.strip().splitlines():
        if line.strip() and not OUTLINE_LINE.match(line):
            line = "- " + line.strip()
        out.append(escape_tags(line))
    return "\n".join(out)


# ---------------------------------------------------------------------------
# Graph setup
# ---------------------------------------------------------------------------


def ensure_graph() -> None:
    graphs = logseq("graph", "list")
    names = {g if isinstance(g, str) else g.get("name") or g.get("graph") for g in
             (graphs if isinstance(graphs, list) else graphs.get("graphs", []))}
    if GRAPH not in names:
        logseq("graph", "create")


def ensure_schema() -> str:
    """Create the tag and properties if missing. Returns the sha property's db ident."""
    logseq("upsert", "tag", "--name", TAG)
    props = logseq("list", "property")
    props = props if isinstance(props, list) else props.get("items", [])
    have = {p.get("block/title"): p.get("db/ident") for p in props}
    for name in [*PROPS.values(), SOURCE_PROP, SHA_PROP]:
        if name not in have:
            logseq("upsert", "property", "--name", name, "--type", "default", "--cardinality", "one")
    if SHA_PROP not in have:
        props = logseq("list", "property")
        props = props if isinstance(props, list) else props.get("items", [])
        have = {p.get("block/title"): p.get("db/ident") for p in props}
    return have[SHA_PROP]


def existing_shas(sha_ident: str) -> dict[str, str]:
    """{page name: pazbrain-sha} for every page that has one."""
    rows = logseq("query", "--query",
                  f"[:find ?n ?v :where [?p :block/name ?n] [?p :{sha_ident} ?e] [?e :block/title ?v]]")
    return {n: v for n, v in (rows or {}).get("result", [])}


def content_children(slug: str) -> list[int]:
    """Top-level content blocks of a page (property-value blocks excluded)."""
    ids = logseq("query", "--query",
                 "[:find [?b ...] :in $ ?n :where [?p :block/name ?n] [?b :block/parent ?p] "
                 "[(missing? $ ?b :logseq.property/created-from-property)]]",
                 "--inputs", f"[{edn_str(slug)}]")
    return sorted((ids or {}).get("result", []))


def stale_property_values(slug: str) -> list[int]:
    """Re-setting a text property makes a new value block and leaves the old one parented to
    the page; these are the value blocks the page no longer points at."""
    ids = logseq("query", "--query",
                 "[:find [?b ...] :in $ ?n :where [?p :block/name ?n] [?b :block/page ?p] "
                 "[?b :logseq.property/created-from-property ?prop] [?prop :db/ident ?a] (not [?p ?a ?b])]",
                 "--inputs", f"[{edn_str(slug)}]")
    return sorted((ids or {}).get("result", []))


# ---------------------------------------------------------------------------
# Ingest
# ---------------------------------------------------------------------------


def ingest_page(slug: str, fm: dict, body: str, rel: str, sha: str, is_new: bool) -> int:
    """Upsert one page. Returns the number of blocks written."""
    props = {}
    for key, prop in PROPS.items():
        val = fm.get(key)
        if val in (None, "", []):
            continue
        props[prop] = ", ".join(map(str, val)) if isinstance(val, list) else str(val)
    props[SOURCE_PROP] = rel
    edn_props = "{" + " ".join(f"{edn_str(k)} {edn_str(v)}" for k, v in props.items())
    if fm.get("summary"):
        edn_props += f" :logseq.property/description {edn_str(str(fm['summary']))}"
    edn_props += "}"

    logseq("upsert", "page", "--page", slug, "--update-tags", f"[{edn_str(TAG)}]",
           "--update-properties", edn_props)

    if not is_new:
        old = content_children(slug)
        if old:
            logseq("remove", "block", "--id", "[" + " ".join(map(str, old)) + "]")

    written = 0
    body = to_outline(body)
    if body:
        with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, encoding="utf-8") as fh:
            fh.write(body + "\n")
            tmp = fh.name
        try:
            os.chmod(tmp, 0o600)
            res = logseq("upsert", "block", "--target-page", slug, "--blocks-file", tmp)
            written = len((res or {}).get("result", []))
        finally:
            os.unlink(tmp)

    # Last: marks the page as done for this source version.
    logseq("upsert", "page", "--page", slug, "--update-properties", f"{{{edn_str(SHA_PROP)} {edn_str(sha)}}}")
    if not is_new:
        stale = stale_property_values(slug)
        if stale:
            logseq("remove", "block", "--id", "[" + " ".join(map(str, stale)) + "]")
    return written


def daemon_running() -> bool:
    try:
        servers = (logseq("server", "list") or {}).get("servers", [])
    except (LogseqError, subprocess.TimeoutExpired):
        return False
    return any(s.get("graph") == GRAPH for s in servers)


def stop_daemon() -> None:
    subprocess.run([LOGSEQ, "server", "stop", "--graph", GRAPH], capture_output=True,
                   env=dict(os.environ, NODE_NO_WARNINGS="1"), timeout=60)


def main() -> int:
    ap = argparse.ArgumentParser(prog="logseq_ingest.py", description=__doc__.split("\n\n")[0])
    ap.add_argument("--dry-run", action="store_true", help="print what would change; write nothing")
    args = ap.parse_args()

    # Leave a daemon that something else started (e.g. a long-lived reader); stop the one this run starts.
    was_running = daemon_running()
    try:
        return ingest(args)
    finally:
        if not was_running:
            stop_daemon()


def ingest(args: argparse.Namespace) -> int:
    counts ={"seen": 0, "created": 0, "updated": 0, "unchanged": 0, "skipped": 0, "errors": 0, "blocks": 0}
    if not args.dry_run:
        ensure_graph()
        sha_ident = ensure_schema()
        known = existing_shas(sha_ident)
    else:
        try:
            known = existing_shas(ensure_schema_readonly())
        except LogseqError:
            known = {}

    slugs_seen: set[str] = set()
    for path in sorted(WIKI.rglob("*.md")):
        rel = str(path.relative_to(WIKI))
        parts = path.relative_to(WIKI).parts
        if path.name in SKIP_FILES or SKIP_DIRS & set(parts) or any(p.startswith(".") for p in parts):
            continue
        counts["seen"] += 1
        raw = path.read_bytes()
        sha = hashlib.sha256(raw).hexdigest()
        try:
            fm, body = parse_page(raw.decode("utf-8", errors="replace"))
        except (ValueError, yaml.YAMLError) as exc:
            counts["skipped"] += 1
            print(f"  skipped   {rel}: {exc}", file=sys.stderr)
            continue
        slug = str(fm.get("slug") or path.stem).lower()
        slugs_seen.add(slug)
        if known.get(slug) == sha:
            counts["unchanged"] += 1
            continue
        action = "updated" if slug in known else "created"
        if args.dry_run:
            print(f"  would {action[:-1]} {slug} <- {rel}")
            counts[action] += 1
            continue
        try:
            counts["blocks"] += ingest_page(slug, fm, body, rel, sha, is_new=slug not in known)
            counts[action] += 1
            print(f"  {action:9} {slug}", file=sys.stderr)
        except (LogseqError, subprocess.TimeoutExpired) as exc:
            counts["errors"] += 1
            print(f"  error     {slug}: {exc}", file=sys.stderr)

    orphans = sorted(set(known) - slugs_seen)
    for slug in orphans:
        print(f"  orphan    {slug} (no wiki file; left in graph)", file=sys.stderr)
    print("logseq_ingest: " + ", ".join(f"{k}={v}" for k, v in counts.items()) + f", orphans={len(orphans)}"
          + (" (dry run)" if args.dry_run else ""))
    return 1 if counts["errors"] else 0


def ensure_schema_readonly() -> str:
    props = logseq("list", "property")
    props = props if isinstance(props, list) else props.get("items", [])
    have = {p.get("block/title"): p.get("db/ident") for p in props}
    if SHA_PROP not in have:
        raise LogseqError("no sha property yet")
    return have[SHA_PROP]


if __name__ == "__main__":
    sys.exit(main())
